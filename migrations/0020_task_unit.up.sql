-- 0020：任务项加「量词」（个 / 颗 / 块 / 堆 …）
--
-- 为什么加：裁判端题卡上写的是「每个 +150」「每颗 +100」（设计册 13 个页面都有这种写法），
-- 而这个「个 / 颗 / 块」此前**无处可配** —— 后台任务配置只有
-- 「任务名 / 评分方式 / 满分 / 权重（每单位分）/ 录入控件」，打分页因此只能渲染
-- 「每单位 N 分」，量词只存在于设计稿的文案里。加列后由后台下发，打分页渲染成
-- 「每{量词} +N 分」，实现与设计册对齐。
--
-- 取值：短文本，**可为空、无默认值**。空 = 「未配置」→ 界面回落成「每单位」。
-- 与仓库既有口径一致（「无记录 = 取代码默认值」）：不给存量行预填，
-- 否则「从来没设过」与「显式设成了同一个值」再也分不开。
--
-- 刻意**不建 CHECK / 不枚举**：量词是文案，穷举必然漏（堆 / 轮 / 张 / 组…），
-- 而枚举一旦漏了，现场配置就会被数据库挡住。合法性交 engine.ValidateEvent 判
-- （非计数项填了量词 → 警告；过长 → 拦下），与「判据写在一处、库只做兜底」的既有约定一致。
--
-- 语义范围：只对 type='count'（计数得分）有意义 —— 数值评分与是否完成都没有「每单位」的概念。
--
-- 兼容性：加列本身向后兼容（老客户端不发该字段 = 空值）；但**反向不兼容** ——
-- 前端一旦开始发 unit，后端必须已经能收（api 用 DisallowUnknownFields，
-- 多一个未知字段会让整条请求 400），所以前后端要一起上。
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS unit TEXT;

COMMENT ON COLUMN tasks.unit IS
    '计数项的量词（个/颗/块/堆…），仅 type=count 有意义；空 = 界面回落「每单位」';
