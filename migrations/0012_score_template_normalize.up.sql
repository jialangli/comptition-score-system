-- ============================================================================
-- 0012：计分规则归一 —— 数据层只留「直接求和」（sum）
--
-- 背景（2026/10/09 口径）：
--   界面早已只提供一种（只读展示，无下拉），Go 引擎的**空值兜底**也已改成 sum。
--   但库里若还留着历史值（weighted_sum / average），就会出现
--   「界面显示『直接求和』、实际按历史口径算分」—— 看着对、算出来错。
--   本迁移把**数据本身**归一，从根上消除这个分叉。
--
-- 影响评估：
--   本赛制从未真正使用过其它模板（三份前端的赛项模板库与内置数据、既有赛事数据
--   都是 sum），所以对现有数据**预期是空操作**；它主要为「外部构造 / 极早期数据」兜底。
--
--   ⚠️ 与 0011 的处理方向相反：0011（enum 下线）是「只放宽约束、不动数据」，
--   这里**动数据**。理由：模板值直接决定算分口径，留着就是隐患；
--   而 enum 只是个不再新增的取值，历史行原样显示即可。
--
-- 语义：template 缺键或为空 → 补成 sum（与 engine.Score 的兜底同口径）。
-- 幂等：重复执行不产生变化。
--
-- ⚠️ 同时刷新 updated_at：增量同步的游标基于它，不刷新的话客户端仍拿着旧模板值算分，
--    等于"库改了、前端没改"。
--
-- 注：Go 引擎仍保留 weighted_sum / average 的算分分支（golden 逐位比对也要用），
--    数据层归一不影响它 —— 只是"库里不会再有这种值"。
-- ============================================================================

BEGIN;

UPDATE events
   SET score_rule = jsonb_set(score_rule, '{template}', '"sum"', true),
       updated_at = now()
 WHERE COALESCE(score_rule->>'template', '') <> 'sum';

COMMENT ON COLUMN events.score_rule IS
    '计分规则；本赛制恒为 sum（直接求和），历史值已由迁移 0012 归一';

COMMIT;
